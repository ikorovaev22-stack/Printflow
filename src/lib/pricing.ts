// ── Price list (stored per company in price_lists.config) ───────────────────────────────────────────

type Toggle<T> = T & { enabled: boolean };

export type CardsPrices = {
  enabled: boolean;
  // Price of one card at each run, single-sided on the base paper (the coefficient 1). Falls as the run grows.
  tiers: Record<`${CardQty}`, number>;
  sizes: Record<CardSize, Toggle<{ coef: number }>>;
  papers: Record<CardPaper, Toggle<{ coef: number }>>;
  duplexCoef: number;
  // Per card, with a minimum charge per order
  lamination: { matte: number; gloss: number; min: number };
  corners: { perPiece: number; min: number };
  urgentPct: number;
};

export type BannersPrices = {
  enabled: boolean;
  materials: Record<BannerMaterial, Toggle<{ perM2: number }>>;
  // Smaller banners are billed as this area, m²
  minArea: number;
  width: { min: number; max: number };
  height: { min: number; max: number };
  grommetPrice: number;
  hemPerM: number;
  pocketPerM: number;
  urgentPct: number;
};

// Own items: any product the owner describes (flyers, certificates, tags…). Ids are generated by the admin form
// and keep the calculator's URL stable while names and prices change.
export type ItemChoice = { id: string; name: string; coef: number };
export type ItemOption = { id: string; name: string; choices: ItemChoice[] };
export type ItemExtra = { id: string; name: string; perPiece: number; min: number };
export type ItemPrices = {
  id: string;
  name: string;
  enabled: boolean;
  // Price of the whole run with the coefficient 1 in every option; runs ascend
  tiers: { qty: number; price: number }[];
  // The client picks one variant in each option; the coefficients multiply the run price
  options: ItemOption[];
  // Switches priced per piece, with a minimum charge per order
  extras: ItemExtra[];
  urgentPct: number;
};

export type PriceList = { cards: CardsPrices; banners: BannersPrices; items: ItemPrices[] };

